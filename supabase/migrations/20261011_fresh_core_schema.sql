begin;

create extension if not exists pgcrypto;

create table if not exists public.search_history (
  id bigint generated by default as identity primary key,
  user_id text not null,
  query text not null default '',
  location text not null default '',
  max_results integer not null default 0 check (max_results >= 0),
  total_scraped integer not null default 0 check (total_scraped >= 0),
  total_qualified integer not null default 0 check (total_qualified >= 0),
  apify_cost_usd numeric(12,4) not null default 0 check (apify_cost_usd >= 0),
  anthropic_cost_usd numeric(12,4) not null default 0 check (anthropic_cost_usd >= 0),
  total_cost_usd numeric(12,4) not null default 0 check (total_cost_usd >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  search_id bigint not null references public.search_history(id) on delete cascade,
  user_id text not null,
  company_name text not null default '',
  website text not null default '',
  phone text not null default '',
  email text not null default '',
  city text not null default '',
  rating text not null default '',
  intent_score text not null default '',
  icp_score text not null default '',
  reasoning text not null default '',
  icp_reasoning text not null default '',
  place_id text not null default '',
  phone_normalized text not null default '',
  website_domain text not null default '',
  email1_subject text,
  email1_body text,
  email2_subject text,
  email2_body text,
  email3_subject text,
  email3_body text,
  email4_subject text,
  email4_body text,
  email5_subject text,
  email5_body text,
  email_framework_key text,
  email_template_key text,
  email_sent_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.product_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id text not null,
  name text not null,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.user_quotas (
  user_id text primary key,
  quota_usd numeric(12,2) not null default 5 check (quota_usd >= 0),
  updated_at timestamptz not null default now()
);

create index if not exists search_history_user_created_idx
  on public.search_history (user_id, created_at desc);
create index if not exists leads_search_id_idx
  on public.leads (search_id);
create index if not exists leads_user_created_idx
  on public.leads (user_id, created_at desc);
create index if not exists leads_user_place_idx
  on public.leads (user_id, place_id) where place_id <> '';
create index if not exists leads_user_phone_idx
  on public.leads (user_id, phone_normalized) where phone_normalized <> '';
create index if not exists leads_user_email_idx
  on public.leads (user_id, lower(email)) where email <> '';
create index if not exists leads_user_domain_idx
  on public.leads (user_id, website_domain) where website_domain <> '';
create index if not exists leads_user_sent_idx
  on public.leads (user_id, email_sent_at) where email_sent_at is not null;
create index if not exists product_profiles_user_updated_idx
  on public.product_profiles (user_id, updated_at desc);
create unique index if not exists product_profiles_user_name_idx
  on public.product_profiles (user_id, lower(name));

alter table public.search_history enable row level security;
alter table public.leads enable row level security;
alter table public.product_profiles enable row level security;
alter table public.user_quotas enable row level security;

-- The browser uses Supabase only for Auth. All table access goes through the
-- Node server with SUPABASE_KEY, whose service role bypasses RLS. Keeping these
-- tables policy-free prevents anon/authenticated clients from reading them.
revoke all on table public.search_history from anon, authenticated;
revoke all on table public.leads from anon, authenticated;
revoke all on table public.product_profiles from anon, authenticated;
revoke all on table public.user_quotas from anon, authenticated;
revoke all on sequence public.search_history_id_seq from anon, authenticated;
revoke all on sequence public.leads_id_seq from anon, authenticated;

commit;
